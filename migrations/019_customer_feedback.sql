-- One-time customer feedback invitation, the answers, and the evidence that decides when to ask.
-- Additive only: three new tables, no existing table, column, constraint or row is changed.

-- A customer clicked "Xem bài Facebook" for one of their own leads. One row per account and Facebook post URL (the same
-- lead counted once, however often it is opened). This records only the click inside QLead, never what happened on
-- Facebook. Rows go away with the account or the post.
CREATE TABLE IF NOT EXISTS lead_source_opens (
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  normalized_url text NOT NULL CHECK (length(normalized_url) BETWEEN 1 AND 2048),
  post_id uuid NOT NULL REFERENCES facebook_posts(id) ON DELETE CASCADE,
  first_opened_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, normalized_url)
);

-- The automatic invitation, at most one row per account. No row = not invited yet ("not eligible" and "eligible but not
-- invited" are computed from lead_source_opens, never stored). 'shown' is claimed atomically by exactly one tab/device;
-- 'submitted' and 'declined' are final and are never reset, so the invitation is never shown automatically again.
CREATE TABLE IF NOT EXISTS customer_feedback_invitations (
  user_id uuid PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  status text NOT NULL CHECK (status IN ('shown', 'submitted', 'declined')),
  shown_at timestamptz,
  responded_at timestamptz,
  -- Lets the tab that claimed the invitation show it again after a reload within a short window (never another tab).
  claim_token uuid,
  CHECK ((status = 'shown') = (responded_at IS NULL))
);

-- The answers. 'invitation' = given through the automatic invitation (at most one per account); 'voluntary' = sent later
-- from "Góp ý cho QLead". A rating is 1-5 or absent; nothing is ever defaulted. submission_id is generated by the browser
-- once per form, so a double click or a retry after a lost response cannot add a second row.
CREATE TABLE IF NOT EXISTS customer_feedback (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  submission_id uuid NOT NULL UNIQUE,
  source text NOT NULL CHECK (source IN ('invitation', 'voluntary')),
  ease_rating smallint CHECK (ease_rating BETWEEN 1 AND 5),
  needs_rating smallint CHECK (needs_rating BETWEEN 1 AND 5),
  unmet_reason text CHECK (unmet_reason IS NULL OR length(unmet_reason) BETWEEN 1 AND 1000),
  improvement text CHECK (improvement IS NULL OR length(improvement) BETWEEN 1 AND 2000),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (ease_rating IS NOT NULL OR needs_rating IS NOT NULL OR unmet_reason IS NOT NULL OR improvement IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS customer_feedback_one_invitation_idx ON customer_feedback(user_id) WHERE source = 'invitation';
CREATE INDEX IF NOT EXISTS customer_feedback_recent_idx ON customer_feedback(created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS customer_feedback_user_idx ON customer_feedback(user_id, created_at DESC);

-- Same protection as the other account tables: only the authenticated Next.js server (privileged connection) reads them.
ALTER TABLE lead_source_opens ENABLE ROW LEVEL SECURITY;
ALTER TABLE customer_feedback_invitations ENABLE ROW LEVEL SECURITY;
ALTER TABLE customer_feedback ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE lead_source_opens, customer_feedback_invitations, customer_feedback FROM PUBLIC;
DO $$
DECLARE role_name text;
BEGIN
  FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated', 'service_role'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
      EXECUTE format('REVOKE ALL ON TABLE lead_source_opens, customer_feedback_invitations, customer_feedback FROM %I', role_name);
    END IF;
  END LOOP;
END $$;
